"""Игра «Угадай число» — бинарный поиск.

Модуль содержит:
- game_core_v3: функция угадывания числа.
- score_game: функция оценки среднего числа попыток.
"""

import numpy as np


def game_core_v3(number: int = 1) -> int:
    """
    Угадывает число с помощью бинарного поиска.

    Args:
        number (int, optional): Загаданное число. Defaults to 1.

    Returns:
        int: Число попыток.
    """
    count = 0
    low = 1
    high = 100

    while True:
        count += 1
        predict = (low + high) // 2

        if predict == number:
            break
        elif predict < number:
            low = predict + 1
        else:
            high = predict - 1

    return count


def score_game(game_core) -> int:
    """
    Запускает игру 1000 раз и считает среднее число попыток.

    Args:
        game_core: Функция угадывания.

    Returns:
        int: Среднее число попыток.
    """
    count_ls = []
    np.random.seed(1)  # фиксируем seed для воспроизводимости

    random_array = np.random.randint(1, 101, size=(1000))

    for number in random_array:
        count_ls.append(game_core(number))

    score = int(np.mean(count_ls))
    print(f"Ваш алгоритм угадывает число в среднем за {score} попыток")

    return score


if __name__ == "__main__":
    score_game(game_core_v3)


# ## Игра «Угадай число» — бинарный поиск
#
# **Задача:** угадать число от 1 до 100 за минимальное число попыток.
#
# **Алгоритм:** бинарный поиск.
#
# **Идея:**
# 1. Загадываем число.
# 2. Делим диапазон **пополам**.
# 3. Сравниваем середину с загаданным:
#    - Если **меньше** — ищем в правой половине.
#    - Если **больше** — в левой.
# 4. Диапазон **сужается вдвое** каждый раз.
#
# **Сложность:** O(log n).
# - Для 100 чисел → **log₂(100) ≈ 7** попыток.
# - Для 1000 чисел → **log₂(1000) ≈ 10**.
# - Для 1 000 000 → **log₂(10⁶) ≈ 20**.
#
# **Результат:** среднее ~**6 попыток** (максимум 7).
#
# **Преимущества:**
# - **Гарантированно** меньше 20 попыток.
# - **Оптимальный** алгоритм для поиска.
# - **Легко масштабируется** (для любого диапазона).
